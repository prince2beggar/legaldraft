def test_decision_d06_rules_engine_compute_provenance_metadata(engine):
    """
    Decision D6 / Trust Kernel:
    compute() returns rule id, rule version, and the exact inputs used,
    so the UI can clearly display how a date was calculated.
    """
    inputs = {
        "start_date": "2026-10-15",
        "days": 45,
        "include_trigger_day": True,
        "calendar": "default",
    }
    res = engine.compute("relative_period.calendar_days.v1", inputs)

    assert res["status"] == "SUCCESS"
    assert res["rule_id"] == "relative_period.calendar_days.v1"
    assert res["rule_version"] == "1.0.0"
    assert res["version"] == "1.0.0"
    assert res["result_date"] == "2026-11-28"

    # Inputs dictionary returned intact for UI explanation
    assert res["inputs"]["start_date"] == "2026-10-15"
    assert res["inputs"]["days"] == 45
    assert res["inputs"]["include_trigger_day"] is True
    assert res["inputs"]["calendar"] == "default"
    assert "explanation" in res
    assert len(res["explanation"]) > 0
