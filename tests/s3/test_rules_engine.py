def test_negative_hr_d6_llm_deadline_invention_rejected(engine):
    """
    SRS HR-D6: Deadlines must NEVER be generated by an LLM.
    Any date calculation must go through the rules engine or be an explicit date stated in the source text.
    """
    # 1. Allowed: Valid computation from Rules Engine
    rule_res = engine.compute(
        "relative_period.calendar_days.v1",
        {"start_date": "2026-10-01", "days": 30}
    )
    assert engine.validate_deadline_provenance("2026-10-31", rule_result=rule_res) is True

    # 2. Allowed: Verbatim date present in statutory source text
    source_passage = "এই নোটিশ প্রাপ্তির ৩০ দিনের মধ্যে, অর্থাৎ ২০২৬-১১-১৫ তারিখের মধ্যে জবাব দিতে হবে।"
    assert engine.validate_deadline_provenance("২০২৬-১১-১৫", source_text=source_passage) is True

    # 3. Strictly Rejected: Unverified deadline invented by LLM
    with pytest.raises(UnverifiedDeadlineError) as exc_info:
        engine.validate_deadline_provenance(
            claimed_date_str="2026-11-25",
            source_text="বাড়িভাড়া আইন ধারা ৭ অনুযায়ী যুক্তিসঙ্গত সময়ের মধ্যে প্রদান করিতে হইবে।",
            rule_result=None
        )
    assert ("Decision D6 Violation" in str(exc_info.value) or "HR-D6 Violation" in str(exc_info.value))
    assert "AI-invented deadlines are strictly forbidden" in str(exc_info.value)


def test_rule_persisted_tests_execution(engine):
    """Runs all seeded tests for relative_period.calendar_days.v1 and verifies 100% pass."""
    outcomes = engine.run_rule_tests("relative_period.calendar_days.v1", "1.0.0")
